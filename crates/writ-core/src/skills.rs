/// Result of skill generation.
#[derive(Debug, Default, serde::Serialize)]
pub struct SkillGenerateResult {
    pub created: usize,
    pub updated: usize,
    pub skipped: usize,
}

/// Generate skill directories in `.claude/skills/`.
pub fn generate_skills(root: &Path) -> WritResult<SkillGenerateResult> {
    let skills_dir = root.join(".claude").join("skills");
    fs::create_dir_all(&skills_dir)?;

    let mut result = SkillGenerateResult::default();

    for template in SKILL_TEMPLATES {
        let skill_dir = skills_dir.join(template.name);
        fs::create_dir_all(&skill_dir)?;

        // Write SKILL.md
        let skill_path = skill_dir.join("SKILL.md");
        let full_content = format!("{}{}", GENERATED_HEADER, template.skill_md);

        if skill_path.exists() {
            let existing = fs::read_to_string(&skill_path).unwrap_or_default();
            if existing == full_content {
                result.skipped += 1;
                // Still check supporting files
            } else {
                atomic_write(&skill_path, full_content.as_bytes())?;
                result.updated += 1;
            }
        } else {
            atomic_write(&skill_path, full_content.as_bytes())?;
            result.created += 1;
        }

        // Write supporting files
        for sf in template.supporting_files {
            let sf_path = skill_dir.join(sf.filename);
            let sf_content = format!("{}{}", GENERATED_HEADER, sf.content);
            if sf_path.exists() {
                let existing = fs::read_to_string(&sf_path).unwrap_or_default();
                if existing != sf_content {
                    atomic_write(&sf_path, sf_content.as_bytes())?;
                }
            } else {
                atomic_write(&sf_path, sf_content.as_bytes())?;
            }
        }
    }

    Ok(result)
}

/// Remove all writ skill directories from `.claude/skills/`.
pub fn remove_skills(root: &Path) -> WritResult<Vec<String>> {
    let skills_dir = root.join(".claude").join("skills");
    if !skills_dir.exists() {
        return Ok(Vec::new());
    }

    let mut removed = Vec::new();

    for entry in fs::read_dir(&skills_dir)? {
        let entry = entry?;
        let name = entry.file_name().to_string_lossy().to_string();

        // Only remove writ-prefixed directories.
        if name.starts_with("writ-") && entry.path().is_dir() {
            fs::remove_dir_all(entry.path())?;
            removed.push(name);
        }
    }

    // Clean up empty skills directory.
    if skills_dir.exists() {
        if fs::read_dir(&skills_dir)?.next().is_none() {
            let _ = fs::remove_dir(&skills_dir);
        }
    }

    Ok(removed)
}

