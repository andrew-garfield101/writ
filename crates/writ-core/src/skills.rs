//! Skill template generation for Claude Code.
//!
//! Generates skill directories in `.claude/skills/` with SKILL.md files
//! and optional supporting files. Skills provide auto-invocation and
//! richer context than slash commands.
//!
//! Skills coexist with slash commands (`.claude/commands/`) — both are
//! generated during `writ init` for maximum compatibility. Slash commands
//! serve older Claude Code versions; skills add auto-invocation and
//! supporting files. Neither replaces the other for beta.

use std::fs;
use std::path::Path;

use crate::error::WritResult;
use crate::fsutil::atomic_write;

/// Header injected at the top of every generated skill file.
const GENERATED_HEADER: &str = "<!-- Generated by writ init. Do not edit. -->\n";

/// A supporting file bundled with a skill (e.g., checklists, guides).
pub struct SupportingFile {
    /// File name (e.g., "reading-context.md").
    pub filename: &'static str,
    /// Markdown content (without the generated header).
    pub content: &'static str,
}

/// A skill template: directory name, SKILL.md content, and supporting files.
pub struct SkillTemplate {
    /// Directory name under `.claude/skills/`, e.g. "writ-context".
    pub name: &'static str,
    /// SKILL.md content including YAML frontmatter (without the generated header).
    pub skill_md: &'static str,
    /// Supporting files to generate alongside SKILL.md.
    pub supporting_files: &'static [SupportingFile],
}

