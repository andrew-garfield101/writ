"""SC.6: Slash command generation integration tests.

Tests the full CLI path for slash command generation/removal via writ init/uninit.
Complements the Rust unit tests in slash_commands.rs with end-to-end verification.
"""

import json
import subprocess
from pathlib import Path

import pytest


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

WRIT_BIN = None
_search = Path(__file__).resolve()
for _ in range(6):
    _search = _search.parent
    for profile in ("release", "debug"):
        candidate = _search / "target" / profile / "writ"
        if candidate.exists():
            WRIT_BIN = str(candidate)
            break
    if WRIT_BIN:
        break

# All 20 expected slash command files (17 original + 3 workspace).
EXPECTED_COMMANDS = [
    "writ-context.md",
    "writ-seal.md",
    "writ-spec-add.md",
    "writ-spec-done.md",
    "writ-status.md",
    "writ-diff.md",
    "writ-log.md",
    "writ-show.md",
    "writ-spec-status.md",
    "writ-spec-show.md",
    "writ-spec-reopen.md",
    "writ-finish.md",
    "writ-summary.md",
    "writ-restore.md",
    "writ-converge.md",
    "writ-verify.md",
    "writ-doctor.md",
    "writ-workspace-create.md",
    "writ-workspace-list.md",
    "writ-workspace-status.md",
]

GENERATED_HEADER = "<!-- Generated by writ init. Do not edit. -->"


def run_writ(args: list, cwd: str, check: bool = True) -> subprocess.CompletedProcess:
    if WRIT_BIN is None:
        pytest.skip("writ binary not found")
    return subprocess.run(
        [WRIT_BIN] + args, capture_output=True, text=True, cwd=cwd, check=check,
    )


def run_git(args: list, cwd: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git"] + args, capture_output=True, text=True, cwd=cwd, check=True,
    )


